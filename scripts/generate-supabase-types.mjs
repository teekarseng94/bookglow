/**
 * Generate packages/database-contracts/src/database.types.ts from a linked Supabase project.
 *
 * Usage:
 *   set SUPABASE_PROJECT_ID=your-ref   (or pass --project-id=)
 *   npm run supabase:types
 *
 * Local stack alternative (after npm run supabase:start):
 *   npx supabase gen types typescript --local > packages/database-contracts/src/database.types.ts
 */
import { spawnSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "packages", "database-contracts", "src", "database.types.ts");

const projectArg = process.argv.find((a) => a.startsWith("--project-id="));
const projectId =
  (projectArg && projectArg.split("=")[1]) ||
  process.env.SUPABASE_PROJECT_ID ||
  process.env.VITE_SUPABASE_PROJECT_ID ||
  "";

mkdirSync(dirname(outFile), { recursive: true });

if (!projectId) {
  const stub = `/**
 * Placeholder Database types — run \\\`npm run supabase:types\\\` with SUPABASE_PROJECT_ID set.
 * Do not hand-author table Row types here.
 */
export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];

export type Database = {
  public: {
    Tables: Record<string, never>;
    Views: Record<string, never>;
    Functions: Record<string, never>;
    Enums: Record<string, never>;
    CompositeTypes: Record<string, never>;
  };
};

export type Tables<T extends keyof Database["public"]["Tables"]> =
  Database["public"]["Tables"][T] extends { Row: infer R } ? R : never;
`;
  writeFileSync(outFile, stub, "utf8");
  console.warn(
    "[supabase:types] No SUPABASE_PROJECT_ID — wrote placeholder types to",
    outFile
  );
  console.warn(
    "Set SUPABASE_PROJECT_ID (project ref) and re-run to generate real types."
  );
  process.exit(0);
}

const result = spawnSync(
  "npx",
  ["supabase", "gen", "types", "typescript", "--project-id", projectId],
  { encoding: "utf8", shell: true, cwd: root }
);

if (result.status !== 0) {
  console.error(result.stderr || result.stdout || "supabase gen types failed");
  process.exit(result.status || 1);
}

const header = `/**
 * AUTO-GENERATED by \\\`npm run supabase:types\\\`.
 * Project: ${projectId}
 * Do not edit by hand.
 */\n\n`;

writeFileSync(outFile, header + (result.stdout || ""), "utf8");
console.log("[supabase:types] Wrote", outFile);
