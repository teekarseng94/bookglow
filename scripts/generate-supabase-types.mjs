/** Generate the shared database contract from a linked project or the local stack. */
import { spawnSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "packages", "database-contracts", "src", "database.types.ts");
const projectArg = process.argv.find((value) => value.startsWith("--project-id="));
const projectId = projectArg?.split("=")[1] || process.env.SUPABASE_PROJECT_ID || process.env.VITE_SUPABASE_PROJECT_ID || "";
const args = projectId
  ? ["supabase", "gen", "types", "typescript", "--project-id", projectId]
  : ["supabase", "--workdir", "migration", "gen", "types", "typescript", "--local"];

const result = spawnSync("npx", args, { encoding: "utf8", shell: true, cwd: root });
if (result.status !== 0) {
  console.error(result.stderr || result.stdout || "supabase gen types failed");
  process.exit(result.status || 1);
}

mkdirSync(dirname(outFile), { recursive: true });
const source = projectId ? `Supabase project ${projectId}` : "local migration workspace";
const header = `/**\n * AUTO-GENERATED by \`npm run supabase:types\`.\n * Source: ${source}\n * Do not edit by hand.\n */\n\n`;
writeFileSync(outFile, header + (result.stdout || ""), "utf8");
console.log("[supabase:types] Wrote", outFile, "from", source);
